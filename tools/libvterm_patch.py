# Builds one patched libvterm source file from the pristine copy in third_party/libvterm.
# Usage: libvterm_patch.py PATCH-PROGRAM PRISTINE-FILE OUTPUT SERIES-FILE [PATCH...]
# PATCH... must be a prefix of the series file (in order). They are applied with --fuzz=0, so
# a patch that no longer fits makes the build fail instead of applying somewhere else.
import os, shutil, subprocess, sys, tempfile

def main():
    patch_prog, pristine, output, series = sys.argv[1:5]
    patches = sys.argv[5:]
    with open(series) as f:
        listed = [l.strip() for l in f if l.strip() and not l.lstrip().startswith('#')]
    names = [os.path.basename(p) for p in patches]
    if names != listed[:len(names)]:
        sys.exit('libvterm_patch.py: patches %s are not the start of %s %s' % (names, series, listed))
    with tempfile.TemporaryDirectory() as tmp:
        cur = os.path.join(tmp, 'cur')
        shutil.copyfile(pristine, cur)
        for p in patches:
            nxt = os.path.join(tmp, 'next')
            r = subprocess.run([patch_prog, '--silent', '--fuzz=0', '--no-backup-if-mismatch', '--force',
                                '-o', nxt, cur, '-i', p], stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            if r.returncode != 0:
                sys.exit('libvterm_patch.py: %s does not apply:\n%s' % (p, r.stdout.decode(errors='replace')))
            os.replace(nxt, cur)
        with open(cur, 'rb') as f:
            data = f.read()
    banner = ('/* GENERATED by tools/libvterm_patch.py from third_party/libvterm/%s\n'
              ' * with: %s. Edit the patches, not this file. */\n' %
              (os.path.relpath(pristine, os.path.join(os.path.dirname(series), '..', 'libvterm')),
               ', '.join(names) if names else '(no patches)')).encode()
    with open(output, 'wb') as f:
        f.write(banner + data)

main()
